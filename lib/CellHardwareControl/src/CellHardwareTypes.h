#ifndef CELL_HARDWARE_TYPES_H
#define CELL_HARDWARE_TYPES_H

#include <Arduino.h>

/**
 * @file CellHardwareTypes.h
 * @brief State enumerations, color types, and event callback interfaces for
 *        Role 4: Cell Hardware & Alert Control.
 */

/**
 * @enum CellState
 * @brief Discrete operational states for each medicine cell state machine.
 */
enum CellState {
    CELL_STATE_IDLE = 0,    /**< Cell is inactive. RGB LED is OFF, servo is closed. */
    CELL_STATE_ALERTING,    /**< Medicine reminder active. RGB LED is RED, buzzer pulsing, servo open. */
    CELL_STATE_CONFIRMED,   /**< Confirm button pressed. RGB LED is GREEN for 1s, servo closed, dose confirmed event dispatched. */
    CELL_STATE_WARNING      /**< Missed dose / warning state. RGB LED is YELLOW. */
};

/**
 * @enum CellColor
 * @brief Logical color definitions for RGB LED representation.
 */
enum CellColor {
    COLOR_OFF = 0,
    COLOR_RED,
    COLOR_GREEN,
    COLOR_YELLOW,
    COLOR_BLUE,
    COLOR_WHITE,
    COLOR_CUSTOM
};

/**
 * @enum HardwareEvent
 * @brief Logical events processed or generated by the hardware module.
 */
enum HardwareEvent {
    HW_EVENT_NONE = 0,
    HW_EVENT_MEDICINE_DUE,     /**< Inbound: Scheduling engine signals a dose is due */
    HW_EVENT_MISSED_DOSE,      /**< Inbound: Dose manager / scheduler signals dose missed */
    HW_EVENT_DOSE_CONFIRMED,   /**< Outbound: Hardware signals confirmation button was pressed */
    HW_EVENT_RESET             /**< Inbound: Manual reset / clear state */
};

/**
 * @brief Callback function type invoked when a cell dose is confirmed by physical button press.
 *        Used by Role 5 (Dose/Stock Manager) to decrement stock and log dose history.
 * @param cellId 0-indexed identifier of the confirmed cell.
 */
typedef void (*DoseConfirmedCallback)(uint8_t cellId);

/**
 * @brief Optional callback function type invoked when a cell changes state.
 *        Used by Role 3 (OLED UI) or system logger to update visual display.
 * @param cellId 0-indexed identifier of the cell.
 * @param oldState Previous state.
 * @param newState New state.
 */
typedef void (*CellStateChangedCallback)(uint8_t cellId, CellState oldState, CellState newState);

/**
 * @brief Convert CellState enum to human-readable string.
 */
inline const char* cellStateToString(CellState state) {
    switch (state) {
        case CELL_STATE_IDLE:      return "IDLE";
        case CELL_STATE_ALERTING:  return "ALERTING (RED)";
        case CELL_STATE_CONFIRMED: return "CONFIRMED (GREEN)";
        case CELL_STATE_WARNING:   return "WARNING/MISSED (YELLOW)";
        default:                   return "UNKNOWN";
    }
}

/**
 * @brief Convert CellColor enum to human-readable string.
 */
inline const char* cellColorToString(CellColor color) {
    switch (color) {
        case COLOR_OFF:    return "OFF";
        case COLOR_RED:    return "RED";
        case COLOR_GREEN:  return "GREEN";
        case COLOR_YELLOW: return "YELLOW";
        case COLOR_BLUE:   return "BLUE";
        case COLOR_WHITE:  return "WHITE";
        default:           return "CUSTOM";
    }
}

#endif // CELL_HARDWARE_TYPES_H
